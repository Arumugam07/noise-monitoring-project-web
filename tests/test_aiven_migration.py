class LocalClient(DatabaseClient):
    # Only the isolated test service bypasses production TLS configuration.
    def __init__(self, uri): self.uri = uri

    @contextmanager
    def connect(self, **kwargs):
        conn = psycopg2.connect(self.uri)
        conn.autocommit = kwargs.get('autocommit', False)
        try:
            yield conn
            if not conn.autocommit: conn.commit()
        except BaseException:
            if not conn.autocommit: conn.rollback()
            raise
        finally:
            conn.close()


def reading(value, dt='2026-10-19T16:00:00+00:00', location='16367'):
    return dict(location_id=location, location_name='Tengah', reading_value=value,
                reading_datetime=dt, created_at='2026-11-03T00:00:00+00:00')


def test_real_queries_upserts_pagination_and_materialized_refresh(pair):
    client = LocalClient(pair[1])
    client.table('meter_readings').upsert(
        [reading(80), reading(81), reading(None, dt='2026-10-19T16:01:00+00:00')],
        on_conflict='location_id,reading_datetime').execute()
    initial = client.table('meter_readings').select('*').order('reading_datetime').execute().data
    assert len(initial) == 2 and initial[0]['reading_value'] == 81
    client.table('meter_readings').upsert([reading(82)], on_conflict='location_id,reading_datetime').execute()
    result = (client.table('meter_readings').select('*', count='exact')
              .gte('reading_datetime', '2026-10-19T16:00:00Z')
              .lt('reading_datetime', '2026-10-19T16:02:00Z')
              .order('reading_datetime').range(0, 0).execute())
    assert result.count == 2 and len(result.data) == 1
    assert result.data[0]['id'] == initial[0]['id']
    assert result.data[0]['reading_value'] == 82
    client.refresh()  # First population uses an ordinary refresh.
    client.refresh()  # Subsequent refresh is concurrent.
    rows = client.table('wide_view_mv').select('Date,Time,16367').order('Time').execute().data
    assert rows[0] == {'Date': '2026-10-20', 'Time': '00:00:00', '16367': 82.0}
    assert rows[1]['16367'] is None
    assert client.date_range().data[0]['max_date'] == '2026-10-20'


