def test_real_catchup_is_verified_rerunnable_and_keeps_ids_and_archive(pair):
    source_client, target_client = map(LocalClient, pair)
    source_client.table('meter_readings').upsert([
        reading(80), reading(None, dt='2026-11-02T15:59:00+00:00'),
        reading(90, dt='2026-11-02T16:00:00+00:00'),  # outside requested SG days
    ], on_conflict='location_id,reading_datetime').execute()
    target_client.table('meter_readings').upsert([reading(20)], on_conflict='location_id,reading_datetime').execute()
    existing_id = target_client.table('meter_readings').select('id').execute().data[0]['id']
    source_client.table('monthly_persisted_summary').upsert([
        dict(location_id='16367',month='2026-10-01',min_db=80,max_db=90,
             duration_minutes=3,incident_count=2,total_duration_minutes=9)
    ], on_conflict='location_id,month,min_db,max_db,duration_minutes').execute()
    source_client.refresh()
    with source_client.connect() as src, src.cursor() as cur:
        cur.execute('REFRESH MATERIALIZED VIEW wide_view_mv_backup')
    for expected_changed in [2, 0]:
        with source_client.connect() as src, target_client.connect() as dst:
            src.set_session(readonly=True,isolation_level='REPEATABLE READ')
            assert copy_readings(src,dst,date(2026,10,20),date(2026,11,2)) == (2,expected_changed)
            copy_summaries(src,dst)
            preserve_backup_snapshot(src,dst)
    result = target_client.table('meter_readings').select('*').order('reading_datetime').execute().data
    assert len(result) == 2 and result[0]['id'] == existing_id
    assert result[0]['reading_value'] == 80 and result[1]['reading_value'] is None
    with target_client.connect() as conn, conn.cursor() as cur:
        cur.execute('SELECT count(*) FROM wide_view_mv_backup_snapshot')
        assert cur.fetchone()[0] == 3
    assert target_client.table('monthly_persisted_summary').select('*').execute().data[0]['incident_count'] == 2
