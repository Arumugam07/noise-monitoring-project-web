def test_connection_overrides_uri_ssl_and_closes_certificate(monkeypatch):
    seen = {}
    conn = Mock()

    def connect(uri, **kwargs):
        seen.update(kwargs)
        assert kwargs['sslmode'] == 'verify-full'
        cert = Path(kwargs['sslrootcert'])
        assert cert.read_text() == 'certificate\n'
        assert cert.stat().st_mode & 0o777 == 0o600
        return conn

    monkeypatch.setattr(psycopg2, 'connect', connect)
    with connection('postgres://user:password@host/db?sslmode=require', 'certificate'):
        pass
    assert not Path(seen['sslrootcert']).exists()
    conn.commit.assert_called_once()
    conn.close.assert_called_once()


def test_failed_connection_transaction_rolls_back_and_closes(monkeypatch):
    conn = Mock()
    monkeypatch.setattr(psycopg2, 'connect', lambda *a, **kw: conn)
    with pytest.raises(RuntimeError):
        with connection('postgres://host/db', 'certificate'):
            raise RuntimeError('database operation failed')
    conn.rollback.assert_called_once()
    conn.close.assert_called_once()
    conn.commit.assert_not_called()


